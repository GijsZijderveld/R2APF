#!/usr/bin/env python3
"""Create an A4-width schematic of RAPF restart and R2APF path repair.

Run from the repository root::

    python scripts/plot_rapf_repair_concept.py

The backdrop is generated by the repository's lunar-map generator. The path
overlays are intentionally schematic: they illustrate the recovery rule and
are not recorded outputs from a benchmark episode. The default code scenario C
uses seed 5073, matching the representative scenario used elsewhere in the
project. Paper labels map code C to paper scenario E (hard).

The influence horizon and repair anchor follow RAPFGlobalPlanner:

    H_influence = R_AO + R_u
    anchor = last existing waypoint whose distance from p_stuck exceeds H.

The comparison RAPF planner clears the current path and starts a new path at
the stuck position. R2APF retains the prefix through the repair anchor, then
generates a new suffix from that anchor.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.lines import Line2D
from matplotlib.patches import Circle, Patch

from planners.rapf_global_planner import RAPFGlobalPlanner
from simulation.env_gen_lunar import generate_lunar_env, make_config

# Match scripts/plot_scenario_difficulty.py.
ROCK_COLOR = "#454545"
CRATER_COLOR = "#e5d4ad"
ROUTE_COLOR = "#0072b2"
RETAINED_COLOR = "#009e73"
ARTIFICIAL_COLOR = "#d55e00"
DISCARDED_COLOR = "#7a7a7a"


def positive(value: str) -> float:
    number = float(value)
    if not np.isfinite(number) or number <= 0:
        raise argparse.ArgumentTypeError("must be finite and positive")
    return number


def nonnegative(value: str) -> float:
    number = float(value)
    if not np.isfinite(number) or number < 0:
        raise argparse.ArgumentTypeError("must be finite and nonnegative")
    return number


def load_influence_radius() -> float:
    """Read RHO_U from the shared planner configuration when available."""
    config_path = ROOT / "configs" / "planners" / "r2apf.json"
    if config_path.exists():
        config = json.loads(config_path.read_text(encoding="utf-8"))
        if "RHO_U" in config:
            return float(config["RHO_U"])
    return float(RAPFGlobalPlanner.DEFAULT_PARAMS["RHO_U"])


def recovery_paths(stuck: np.ndarray, horizon: float):
    """Return an illustrative old path, its repair anchor, and new suffixes."""
    # The approach enters the influence horizon before local-minimum detection.
    offsets = np.array([
        [-5.1, -3.4], [-4.0, -2.6], [-3.0, -1.85],
        [-2.7, -0.9], [-1.4, -0.45], [0.0, 0.0],
    ])
    old_path = stuck + offsets
    distances = np.linalg.norm(old_path - stuck, axis=1)
    candidates = np.flatnonzero(distances > horizon)
    if len(candidates) == 0:
        raise ValueError("The schematic old path has no waypoint outside the influence horizon")
    anchor_index = int(candidates[-1])
    anchor = old_path[anchor_index]

    # RAPF discards the old path and grows a fresh path from p_stuck.
    rapf_suffix = stuck + np.array([
        [0.0, 0.0], [0.65, -0.48], [1.7, -0.55],
        [2.55, 0.05], [3.3, 1.05], [4.25, 1.65],
    ])

    # R2APF preserves the prefix and grows from the last waypoint outside H.
    r2apf_suffix = stuck + np.array([
        [-2.7, -0.9], [-3.35, 0.1], [-2.9, 1.55],
        [-1.65, 2.65], [0.15, 3.05], [1.95, 2.55], [3.5, 1.95],
    ])
    return old_path, anchor_index, rapf_suffix, r2apf_suffix


def draw_map(ax, obstacles, center, half_width):
    """Draw the local crop in the colors used by the scenario-map figure."""
    xmin, xmax = center[0] - half_width, center[0] + half_width
    ymin, ymax = center[1] - half_width, center[1] + half_width
    for kind in ("crater", "rock"):
        for obstacle in obstacles:
            if obstacle.kind == kind:
                ax.add_patch(Circle(
                    obstacle.center,
                    obstacle.radius,
                    facecolor=CRATER_COLOR if kind == "crater" else ROCK_COLOR,
                    edgecolor="#76633e" if kind == "crater" else "black",
                    linewidth=0.65 if kind == "crater" else 0.4,
                    zorder=2 if kind == "crater" else 3,
                ))
    ax.set(xlim=(xmin, xmax), ylim=(ymin, ymax),
           xlabel="x [m]", ylabel="y [m]")
    ax.set_aspect("equal", adjustable="box")
    ax.set_axisbelow(True)
    ax.grid(color="0.9", linewidth=0.5, zorder=0)
    ax.tick_params(length=3, pad=3, labelsize=10)


def draw_horizon(ax, stuck, artificial_radius, horizon):
    """Mark the artificial obstacle and its full influence horizon."""
    ax.add_patch(Circle(stuck, horizon, facecolor="none", edgecolor=ARTIFICIAL_COLOR,
                        linewidth=1.35, linestyle=(0, (4, 2)), zorder=5))
    ax.add_patch(Circle(stuck, artificial_radius, facecolor=ARTIFICIAL_COLOR,
                        edgecolor=ARTIFICIAL_COLOR, alpha=0.38,
                        linewidth=1.0, zorder=6))
    ax.plot(*stuck, marker="x", color="black", markersize=7,
            markeredgewidth=1.5, zorder=9)


def draw_arrow(ax, points, index, color, lw=1.8):
    """Add one directional arrow to a polyline."""
    if index + 1 >= len(points):
        return
    a, b = points[index], points[index + 1]
    fraction = 0.72
    start = a + fraction * (b - a)
    end = a + min(0.97, fraction + 0.16) * (b - a)
    ax.annotate("", xy=end, xytext=start,
                arrowprops={"arrowstyle": "-|>", "color": color,
                            "linewidth": lw, "mutation_scale": 10},
                zorder=10)


def create_figure(scenario="C", seed=5073, width_mm=210.0, font_size=10.0,
                  artificial_radius=None, influence_radius=None,
                  stuck_x=15.0, stuck_y=15.0, half_width=5.8):
    if artificial_radius is None:
        artificial_radius = float(RAPFGlobalPlanner.DEFAULT_PARAMS["ARTIFICIAL_R"])
    if influence_radius is None:
        influence_radius = load_influence_radius()
    horizon = artificial_radius + influence_radius
    stuck = np.array([stuck_x, stuck_y], dtype=float)

    style = {
        "font.family": "DejaVu Sans", "font.size": font_size,
        "axes.labelsize": font_size, "xtick.labelsize": font_size,
        "ytick.labelsize": font_size, "legend.fontsize": font_size,
        "pdf.fonttype": 42, "ps.fonttype": 42, "svg.fonttype": "none",
    }
    with plt.rc_context(style):
        config = make_config(scenario, seed=seed)
        obstacles = generate_lunar_env(config)
        old_path, anchor_index, rapf_suffix, r2apf_suffix = recovery_paths(stuck, horizon)
        anchor = old_path[anchor_index]

        fig, axes = plt.subplots(1, 2, figsize=(width_mm / 25.4, 180 / 25.4),
                                 sharex=True, sharey=True)
        fig.subplots_adjust(left=0.075, right=0.985, bottom=0.39,
                            top=0.82, wspace=0.17)
        fig.suptitle("Local-minimum recovery: full restart and partial-trajectory repair",
                     fontsize=font_size + 2, fontweight="bold", y=0.965)
        fig.text(0.5, 0.905,
                 "Same local event and map crop; only the recovery rule changes",
                 ha="center", va="center", fontsize=font_size)

        for ax in axes:
            draw_map(ax, obstacles, stuck, half_width)
            draw_horizon(ax, stuck, artificial_radius, horizon)
            ax.set_xticks(np.arange(np.ceil(stuck_x - half_width),
                                    np.floor(stuck_x + half_width) + 1, 2))
            ax.set_yticks(np.arange(np.ceil(stuck_y - half_width),
                                    np.floor(stuck_y + half_width) + 1, 2))
            # The old trajectory before insertion of the artificial obstacle.
            ax.plot(old_path[:, 0], old_path[:, 1], color=DISCARDED_COLOR,
                    linestyle=(0, (3, 2)), linewidth=1.35, marker=".",
                    markersize=4, zorder=7)
            # Point labels are deliberately kept outside the artificial disk.
            ax.annotate("$p_{\\rm stuck}$", xy=stuck, xytext=(0.35, -0.55),
                        textcoords="offset points", fontsize=font_size,
                        ha="left", va="top", zorder=12,
                        bbox={"boxstyle": "round,pad=0.15", "fc": "white",
                              "ec": "none", "alpha": 0.82})

        axes[0].set_title("RAPF — full restart", fontsize=font_size + 1,
                          fontweight="bold", pad=9)
        axes[1].set_title("R2APF — partial-trajectory repair", fontsize=font_size + 1,
                          fontweight="bold", pad=9)

        # RAPF: no prior path segment is reused; the new path grows from p_stuck.
        axes[0].plot(rapf_suffix[:, 0], rapf_suffix[:, 1], color=ROUTE_COLOR,
                     linewidth=2.2, zorder=8)
        draw_arrow(axes[0], rapf_suffix, 2, ROUTE_COLOR)

        # R2APF: preserve the prefix through the last waypoint outside H.
        prefix = old_path[:anchor_index + 1]
        affected = old_path[anchor_index:]
        axes[1].plot(prefix[:, 0], prefix[:, 1], color=RETAINED_COLOR,
                     linewidth=2.5, marker="o", markersize=3.5, zorder=8)
        axes[1].plot(affected[:, 0], affected[:, 1], color=DISCARDED_COLOR,
                     linestyle=(0, (3, 2)), linewidth=1.5, marker=".",
                     markersize=4, zorder=8)
        axes[1].plot(r2apf_suffix[:, 0], r2apf_suffix[:, 1], color=ROUTE_COLOR,
                     linewidth=2.2, zorder=9)
        axes[1].plot(*anchor, marker="o", color=RETAINED_COLOR,
                     markeredgecolor="black", markeredgewidth=0.5,
                     markersize=6, zorder=11)
        draw_arrow(axes[1], r2apf_suffix, 2, ROUTE_COLOR)
        axes[1].annotate("$a$", xy=anchor, xytext=(8, 8),
                         textcoords="offset points", fontsize=font_size,
                         ha="left", va="bottom",
                         arrowprops={"arrowstyle": "->", "color": RETAINED_COLOR,
                                     "linewidth": 1.0},
                         bbox={"boxstyle": "round,pad=0.15", "fc": "white",
                               "ec": "none", "alpha": 0.88}, zorder=13)
        fig.text(0.5, 0.30,
                 "RAPF clears the path and resumes at $p_{\\rm stuck}$; "
                 "R2APF keeps the prefix and resumes at anchor $a$.",
                 ha="center", va="center", fontsize=font_size)

        legend_handles = [
            Line2D([], [], color=DISCARDED_COLOR, linestyle=(0, (3, 2)),
                   linewidth=1.5, label="Previously planned path"),
            Line2D([], [], color=RETAINED_COLOR, linewidth=2.5,
                   label="Retained prefix"),
            Line2D([], [], color=ROUTE_COLOR, linewidth=2.2,
                   label="Newly planned segment"),
            Patch(facecolor=ARTIFICIAL_COLOR, edgecolor=ARTIFICIAL_COLOR,
                  alpha=0.38, label="Artificial obstacle"),
            Line2D([], [], color=ARTIFICIAL_COLOR, linestyle=(0, (4, 2)),
                   linewidth=1.35, label="Influence horizon $H$"),
        ]
        fig.legend(handles=legend_handles, loc="lower center",
                   bbox_to_anchor=(0.5, 0.22), ncol=3, frameon=False,
                   columnspacing=1.15, handlelength=1.7, handletextpad=0.5)
        fig.text(0.5, 0.112,
                 rf"$H_{{\mathrm{{influence}}}}=R_{{AO}}+R_u="
                 rf"{artificial_radius:.2f}+{influence_radius:.2f}="
                 rf"{horizon:.2f}\,\mathrm{{m}}$; anchor $a$ is the last "
                 rf"waypoint with $\|p_i-p_{{\mathrm{{stuck}}}}\|_2>H_{{\mathrm{{influence}}}}$.",
                 ha="center", va="center", fontsize=font_size)
        paper_scenario = {"A": "A", "E": "C", "C": "E", "D": "D", "B": "B"}[scenario]
        fig.text(0.5, 0.052,
                 f"Procedural map: code {scenario} (paper {paper_scenario}), seed {seed}. "
                 "Path overlays are schematic, not recorded planner trajectories.",
                 ha="center", va="center", fontsize=font_size)

        fig.canvas.draw()
        renderer = fig.canvas.get_renderer()
        for artist in [*fig.texts, *fig.legends]:
            extent = artist.get_window_extent(renderer)
            if extent.width and (not fig.bbox.contains(*extent.min)
                                 or not fig.bbox.contains(*extent.max)):
                label = artist.get_text() if hasattr(artist, "get_text") else "legend"
                raise ValueError(f"Text extends outside the figure ({label!r}); "
                                 "increase figure width")

    metadata = {
        "scenario_code": scenario, "paper_scenario": paper_scenario, "seed": seed,
        "width_mm": width_mm, "font_size_pt": font_size,
        "stuck_xy_m": stuck.tolist(), "artificial_obstacle_radius_m": artificial_radius,
        "repulsive_influence_radius_m": influence_radius,
        "influence_horizon_m": horizon, "repair_anchor_xy_m": anchor.tolist(),
        "repair_anchor_distance_m": float(np.linalg.norm(anchor - stuck)),
        "overlay_type": "schematic; not a recorded benchmark trajectory",
    }
    return fig, metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--scenario", choices=("A", "B", "C", "D", "E"), default="C")
    parser.add_argument("--seed", type=int, default=5073)
    parser.add_argument("--width-mm", type=positive, default=210.0)
    parser.add_argument("--font-size", type=positive, default=10.0)
    parser.add_argument("--artificial-radius", type=positive, default=None)
    parser.add_argument("--influence-radius", type=positive, default=None,
                        help="R_u, default read from configs/planners/r2apf.json")
    parser.add_argument("--stuck-x", type=float, default=15.0)
    parser.add_argument("--stuck-y", type=float, default=15.0)
    parser.add_argument("--half-width", type=positive, default=5.8,
                        help="Half-width in metres of the local map crop")
    parser.add_argument("--dpi", type=int, default=300)
    parser.add_argument("--output", type=Path,
                        default=ROOT / "figures" / "rapf_repair_concept",
                        help="Output stem; writes .pdf, .svg, .png and .json")
    args = parser.parse_args()
    if args.dpi <= 0:
        parser.error("--dpi must be positive")
    fig, metadata = create_figure(
        scenario=args.scenario, seed=args.seed, width_mm=args.width_mm,
        font_size=args.font_size, artificial_radius=args.artificial_radius,
        influence_radius=args.influence_radius, stuck_x=args.stuck_x,
        stuck_y=args.stuck_y, half_width=args.half_width)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    # Avoid bbox_inches='tight': it would change the requested physical width.
    for extension in ("pdf", "svg", "png"):
        target = args.output.with_suffix("." + extension)
        fig.savefig(target, dpi=args.dpi, facecolor="white")
        print(f"Saved {target}")
    args.output.with_suffix(".json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    plt.close(fig)
    print(f"Influence horizon H = {metadata['influence_horizon_m']:.3f} m")
    print(f"Anchor distance = {metadata['repair_anchor_distance_m']:.3f} m (> H)")


if __name__ == "__main__":
    main()
